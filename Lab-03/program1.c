#include <stdio.h>

int main()
{
    int age = 18;
    float percentage = 85.5;
    char grade = 'A';
    double salary = 25000.75;

    printf("Integer Value: %d\n", age);
    printf("Float Value: %.2f\n", percentage);
    printf("Character Value: %c\n", grade);
    printf("Double Value: %.2lf\n", salary);

    return 0;
}
